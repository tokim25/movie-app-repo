// Load-time fix: index.html used to load the catalog as 12 separate
// `<script src="data-*.js">` tags, each a blocking round trip before the app
// could build MOVIES or render anything -- a real contributor to slow first
// visits (repeat visits were fine once the service worker had everything
// cached). The per-studio/per-batch source files are still the real source
// of truth the movie-watchlist-updater skill writes to -- this script just
// concatenates them, in the same order they used to load in, into one file
// index.html loads instead.
//
// Usage:
//   node scripts/bundle-data.mjs          -- write data-bundle.js
//   node scripts/bundle-data.mjs --check  -- exit 1 if data-bundle.js is stale
//     (wired into validate-data.mjs, same pattern as data-version.mjs's
//     --check, so a forgotten re-bundle is caught the same way a forgotten
//     DATA_VERSION re-stamp already is)

import fs from 'node:fs';
import { dataFiles } from './data-version.mjs';

const BUNDLE_PATH = 'data-bundle.js';
const BANNER = '// Auto-generated by `node scripts/bundle-data.mjs` -- do not edit directly.\n' +
  '// Edit the individual data-*.js source files instead, then re-run the bundler.\n\n';

export function computeBundleContent() {
  return BANNER + dataFiles.map(file => fs.readFileSync(file, 'utf8').trimEnd()).join('\n') + '\n';
}

function main() {
  const check = process.argv.includes('--check');
  const expected = computeBundleContent();
  const current = fs.existsSync(BUNDLE_PATH) ? fs.readFileSync(BUNDLE_PATH, 'utf8') : null;

  if (check) {
    if (current !== expected) {
      console.error(`bundle-data: ${BUNDLE_PATH} is stale. Run \`node scripts/bundle-data.mjs\` and commit the result.`);
      process.exit(1);
    }
    console.log(`bundle-data: ${BUNDLE_PATH} is in sync.`);
    return;
  }

  if (current === expected) {
    console.log(`bundle-data: already in sync.`);
    return;
  }

  fs.writeFileSync(BUNDLE_PATH, expected);
  console.log(`bundle-data: wrote ${BUNDLE_PATH} (${(expected.length / 1024).toFixed(0)} KB) from ${dataFiles.length} source files.`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
